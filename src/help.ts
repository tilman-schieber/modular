export const KNOB_HOW = 'DRAG UP/DOWN OR WHEEL. SHIFT = FINE. DOUBLE-CLICK RESETS. ALT+CLICK = MIDI LEARN.';

export function jackHelp(type: string, p: Port) {
  const kind = { trig: 'GATE', cv: 'CV', audio: 'AUDIO' }[p.type];
  return {
    title: `${p.label || p.id.toUpperCase()} - ${kind} ${p.dir === 'in' ? 'IN' : 'OUT'}`,
    text: HELP[type]?.jacks?.[p.id] ?? JACK_KIND[p.type][p.dir === 'in' ? 0 : 1],
  };
}

export function knobHelp(type: string, k: Knob) {
  const own = HELP[type]?.knobs?.[k.id];
  return { title: `${k.label || 'LEVEL'} KNOB`, text: own ? `${own} ${KNOB_HOW}` : KNOB_HOW };
}

